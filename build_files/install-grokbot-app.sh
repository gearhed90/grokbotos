#!/bin/bash
# Bake the Grok Bot Linux app into the image, or leave the placeholder.
#
# One interface at runtime: /usr/local/bin/grokbot-launch reads
# /etc/grokbot/app.conf. This script is the only writer of that choice
# during the image build.
#
# Inputs (environment, from Containerfile ARGs or the caller):
#   GROKBOT_APP_SOURCE   https URL or absolute path. Optional.
#   GROKBOT_APP_SHA256   64 hex chars. Required when a payload is installed.
#   GROKBOT_APP_KIND     auto|appimage|rpm|deb|flatpak|binary. Default auto.
#   GROKBOT_APP_EXEC     absolute path of the installed binary (rpm, deb, binary).
#   GROKBOT_FLATPAK_ID   flatpak application id when KIND=flatpak.
#   GROKBOT_WEB_URL      placeholder web app URL. Empty shows the local page.
#   GROKBOT_LOCAL_PAYLOAD  default /ctx/grokbot-app/payload
#   GROKBOT_DESTDIR      prefix for tests. Empty writes to the image root.
#   GROKBOT_SKIP_PACKAGE_INSTALL=1  skip dnf/flatpak/ar (tests only).
#
# A missing payload installs the placeholder. It does not invent an app.
set -euo pipefail

DESTDIR="${GROKBOT_DESTDIR:-}"
SOURCE="${GROKBOT_APP_SOURCE:-}"
SHA="${GROKBOT_APP_SHA256:-}"
KIND="${GROKBOT_APP_KIND:-auto}"
APP_EXEC="${GROKBOT_APP_EXEC:-}"
FLATPAK_ID="${GROKBOT_FLATPAK_ID:-}"
WEB_URL="${GROKBOT_WEB_URL:-}"
LOCAL_PAYLOAD="${GROKBOT_LOCAL_PAYLOAD:-/ctx/grokbot-app/payload}"
SUMS_FILE="${GROKBOT_SHA256SUMS:-/ctx/grokbot-app/SHA256SUMS}"
SKIP="${GROKBOT_SKIP_PACKAGE_INSTALL:-}"

if [[ -z "$DESTDIR" && "$(id -u)" -ne 0 ]]; then
    echo "install-grokbot-app.sh: refusing to write / without root; set GROKBOT_DESTDIR" >&2
    exit 1
fi

die() {
    echo "install-grokbot-app.sh: $*" >&2
    exit 1
}

assert_safe_assignment() {
    local value="$1"
    local label="$2"
    case "$value" in
        *[$'\n"$\`\\']*) die "unsafe characters in ${label}" ;;
    esac
}

assert_abs_exec() {
    local value="$1"
    [[ "$value" =~ ^/[A-Za-z0-9._@+/-]+$ ]] || die "GROKBOT_APP_EXEC must be a simple absolute path"
}

write_conf() {
    local mode="$1"
    local web="$2"
    local app_id="$3"
    local exec_path="$4"
    assert_safe_assignment "$mode" "mode"
    assert_safe_assignment "$web" "GROKBOT_WEB_URL"
    assert_safe_assignment "$app_id" "app id"
    assert_safe_assignment "$exec_path" "exec"
    if [[ -n "$web" ]]; then
        case "$web" in
            https://* | http://* | file://*) ;;
            *) die "GROKBOT_WEB_URL must start with http://, https://, or file://" ;;
        esac
    fi
    [[ "$app_id" =~ ^[A-Za-z][A-Za-z0-9_.-]*$ ]] || die "unsafe app id"
    install -d -m 0755 "${DESTDIR}/etc/grokbot"
    cat >"${DESTDIR}/etc/grokbot/app.conf" <<EOF
# Generated by build_files/install-grokbot-app.sh.
# Root-owned trusted config. grokbot-launch is the only boot entry.
GROKBOT_MODE="${mode}"
GROKBOT_WEB_URL="${web}"
GROKBOT_APP_ID="${app_id}"
GROKBOT_EXEC="${exec_path}"
EOF
    chmod 644 "${DESTDIR}/etc/grokbot/app.conf"
}

write_wrapper() {
    local body="$1"
    install -d -m 0755 "${DESTDIR}/usr/lib/grokbot"
    printf '%s\n' '#!/bin/bash' 'set -euo pipefail' "$body" \
        >"${DESTDIR}/usr/lib/grokbot/grokbot-native"
    chmod 755 "${DESTDIR}/usr/lib/grokbot/grokbot-native"
}

verify_sha256() {
    local file="$1"
    local expected="$2"
    [[ "$expected" =~ ^[0-9a-fA-F]{64}$ ]] || die "checksum must be 64 hex characters"
    local actual
    actual=$(sha256sum -- "$file" | awk '{print $1}')
    if [[ "${actual,,}" != "${expected,,}" ]]; then
        die "checksum mismatch (expected ${expected}, actual ${actual})"
    fi
}

if [[ -z "$SHA" && -f "$SUMS_FILE" && -f "$LOCAL_PAYLOAD" && -z "$SOURCE" ]]; then
    SHA=$(awk 'NF { print $1; exit }' "$SUMS_FILE")
fi

have_payload=0
if [[ -n "$SOURCE" || -f "$LOCAL_PAYLOAD" ]]; then
    have_payload=1
fi

if [[ "$have_payload" -eq 0 ]]; then
    write_conf "placeholder" "$WEB_URL" "firefox" ""
    echo "install-grokbot-app.sh: no Grok Bot payload; placeholder config written"
    exit 0
fi

[[ -n "$SHA" ]] || die "payload requires a checksum (GROKBOT_APP_SHA256 or grokbot-app/SHA256SUMS)"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
blob="${work}/payload"

if [[ -n "$SOURCE" ]]; then
    case "$SOURCE" in
        https://*)
            curl -fsSL --retry 3 --retry-delay 2 -o "$blob" "$SOURCE"
            ;;
        /*)
            [[ -f "$SOURCE" ]] || die "GROKBOT_APP_SOURCE is not a file: ${SOURCE}"
            cp -- "$SOURCE" "$blob"
            ;;
        *)
            die "GROKBOT_APP_SOURCE must be an https:// URL or an absolute path"
            ;;
    esac
    base_name=$(basename "${SOURCE%%\?*}")
else
    cp -- "$LOCAL_PAYLOAD" "$blob"
    base_name="payload"
fi

[[ -s "$blob" ]] || die "payload is empty"
verify_sha256 "$blob" "$SHA"

if [[ "$KIND" == "auto" ]]; then
    case "$base_name" in
        *.AppImage | *.appimage) KIND="appimage" ;;
        *.rpm) KIND="rpm" ;;
        *.deb) KIND="deb" ;;
        *.flatpak) KIND="flatpak" ;;
        payload)
            # Extension-less repo drop. Caller must name the kind.
            die "grokbot-app/payload has no extension; set GROKBOT_APP_KIND"
            ;;
        *) KIND="binary" ;;
    esac
fi

case "$KIND" in
    appimage)
        install -d -m 0755 "${DESTDIR}/usr/lib/grokbot"
        install -m 0755 "$blob" "${DESTDIR}/usr/lib/grokbot/grokbot.AppImage"
        write_wrapper 'if [[ ! -e /dev/fuse ]]; then export APPIMAGE_EXTRACT_AND_RUN=1; fi
exec /usr/lib/grokbot/grokbot.AppImage "$@"'
        write_conf "native" "" "grokbot" "/usr/lib/grokbot/grokbot-native"
        ;;
    binary)
        if [[ -n "$APP_EXEC" ]]; then
            assert_abs_exec "$APP_EXEC"
        else
            APP_EXEC="/usr/lib/grokbot/grokbot"
        fi
        if [[ "$APP_EXEC" == "/usr/lib/grokbot/grokbot" ]]; then
            install -d -m 0755 "${DESTDIR}/usr/lib/grokbot"
            install -m 0755 "$blob" "${DESTDIR}/usr/lib/grokbot/grokbot"
        elif [[ -z "$SKIP" ]]; then
            install -d -m 0755 "${DESTDIR}$(dirname "$APP_EXEC")"
            install -m 0755 "$blob" "${DESTDIR}${APP_EXEC}"
        fi
        write_wrapper "exec ${APP_EXEC} \"\$@\""
        write_conf "native" "" "grokbot" "/usr/lib/grokbot/grokbot-native"
        ;;
    rpm | deb)
        [[ -n "$APP_EXEC" ]] || die "GROKBOT_APP_EXEC is required for ${KIND}"
        assert_abs_exec "$APP_EXEC"
        if [[ -n "$DESTDIR" && -z "$SKIP" ]]; then
            die "${KIND} install does not honor GROKBOT_DESTDIR; use the image build"
        fi
        if [[ -z "$SKIP" ]]; then
            if [[ "$KIND" == "rpm" ]]; then
                dnf5 install -y "$blob"
            else
                dnf5 install -y binutils tar
                (cd "$work" && ar x "$blob")
                data_tar=$(find "$work" -maxdepth 1 -type f -name 'data.tar.*' -print -quit)
                [[ -n "$data_tar" ]] || die "deb did not contain data.tar.*"
                tar -C "${DESTDIR}/" -xf "$data_tar"
            fi
        fi
        write_wrapper "exec ${APP_EXEC} \"\$@\""
        write_conf "native" "" "grokbot" "/usr/lib/grokbot/grokbot-native"
        ;;
    flatpak)
        [[ "$FLATPAK_ID" =~ ^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+$ ]] \
            || die "GROKBOT_FLATPAK_ID must look like org.example.App"
        if [[ -n "$DESTDIR" && -z "$SKIP" ]]; then
            die "flatpak install does not honor GROKBOT_DESTDIR; use the image build"
        fi
        if [[ -z "$SKIP" ]]; then
            flatpak install --system -y "$blob"
        fi
        write_wrapper "exec /usr/bin/flatpak run ${FLATPAK_ID} \"\$@\""
        write_conf "native" "" "grokbot" "/usr/lib/grokbot/grokbot-native"
        ;;
    *)
        die "unknown GROKBOT_APP_KIND: ${KIND}"
        ;;
esac

echo "install-grokbot-app.sh: installed kind=${KIND} mode=native"
